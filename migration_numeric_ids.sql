-- ============================================================
-- MIGRATIE: Persoon ID naar Numeriek (Auto-increment)
-- ============================================================

-- Stap 1: Schakel foreign key checks even uit (indien nodig, in Supabase vaak niet nodig via UI, maar safe in SQL)
-- In Supabase/Postgres doen we dit door de constraints te droppen en later terug te zetten.

-- Stap 2: Voeg een tijdelijke kolom toe om de Smartschool ID's te bewaren
ALTER TABLE persoon ADD COLUMN IF NOT EXISTS ss_id TEXT;

-- Stap 3: Kopieer de huidige tekst-ID naar ss_id (voor leerlingen die al ingelogd hebben)
UPDATE persoon SET ss_id = id WHERE ss_id IS NULL;

-- Stap 4: Verwijder de primary key constraint op persoon.id
-- Hiervoor moeten we eerst de foreign keys in andere tabellen droppen.
ALTER TABLE reservering DROP CONSTRAINT IF EXISTS reservering_persoon_id_fkey;
ALTER TABLE log DROP CONSTRAINT IF EXISTS log_persoon_id_fkey;

-- Stap 5: Verander de id kolom van persoon naar numeriek met auto-increment
-- Dit is lastig direct te doen op een PK kolom met data. 
-- De veiligste manier is: een nieuwe id kolom maken en de oude weggooien.

ALTER TABLE persoon RENAME COLUMN id TO old_id;
ALTER TABLE persoon ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- Stap 6: Update de foreign keys in reservering en log
-- We moeten de tekst-ID's daar ook omzetten naar de nieuwe numerieke ID's
ALTER TABLE reservering ADD COLUMN persoon_id_new BIGINT;
UPDATE reservering r SET persoon_id_new = p.id FROM persoon p WHERE r.persoon_id = p.old_id;

ALTER TABLE log ADD COLUMN persoon_id_new BIGINT;
UPDATE log l SET persoon_id_new = p.id FROM persoon p WHERE l.persoon_id = p.old_id;

-- Stap 7: Maak de nieuwe ID de primary key
ALTER TABLE persoon DROP COLUMN old_id;
ALTER TABLE persoon ADD PRIMARY KEY (id);

-- Stap 8: Maak de foreign key kolommen definitief
ALTER TABLE reservering DROP COLUMN persoon_id;
ALTER TABLE reservering RENAME COLUMN persoon_id_new TO persoon_id;
ALTER TABLE reservering ADD CONSTRAINT reservering_persoon_id_fkey FOREIGN KEY (persoon_id) REFERENCES persoon(id) ON DELETE CASCADE;

ALTER TABLE log DROP COLUMN persoon_id;
ALTER TABLE log RENAME COLUMN persoon_id_new TO persoon_id;
ALTER TABLE log ADD CONSTRAINT log_persoon_id_fkey FOREIGN KEY (persoon_id) REFERENCES persoon(id) ON DELETE CASCADE;

-- Stap 9: Optioneel: Maak ss_id uniek (om dubbele koppelingen te voorkomen)
CREATE UNIQUE INDEX IF NOT EXISTS idx_persoon_ss_id ON persoon(ss_id) WHERE ss_id IS NOT NULL;

